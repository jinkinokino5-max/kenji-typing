// 作品（ステージ）データの共通型。
//
// 【テキストの出典について】
// text（表示用本文）は、宮沢賢治のパブリックドメイン作品（青空文庫）に基づく。
// 物語編は長い一文を適度に区切り、印象的な語句を抜き出す方針で編集している。
// 詩歌編は原則、詩の全文をもれなく採用する（一部区切りのみの抜粋は行わない）。
// text は原典どおり（歴史的仮名遣いを含む）を保持する。
//
// kana（タイピング対象の読み／かな行表示にも使用）は、原文を音読したときの
// 「口語の発音」でひらがな表記する。句読点等の記号は許容する（2026-07-04改訂。
// 旧仕様は記号なし。既存データの遡及対応は未実施＝reference/引継ぎ資料.md参照）。
// 例：ゐる→いる／つたへて→つたえて／おまへ→おまえ／さう→そう。
// text は原典の表記を保つ一方、kana は現代の発音に変換する、という非対称が
// このアプリの問題文データの基本形（詳細・変換例一覧は
// reference/問題文データ仕様.md を参照）。
// なお入力判定は歴史的仮名遣いのまま書かれた kana も受理する（ゐる=iru、
// さう=sou、おまへ=omae 等）。変換漏れがあっても詰まらないための保険であり、
// 上の原則自体は変わらない。規則の詳細は reference/入力判定仕様.md を参照。
// 正式公開前に青空文庫原典との校合を推奨（URLは企画書 参考資料を参照）。

// 特別章『オノマトペの野原』で、打鍵に同期させる情景エフェクトの種別。
// 通常章では未指定（背景は反応しない）。
export type OnomaFx = "wind" | "water" | "light";

export interface Question {
  id: number;
  /** 表示用の本文（漢字・カタカナ・記号を含む）。 */
  text: string;
  /** タイピング対象の読み（ひらがなのみ／記号なし）。 */
  kana: string;
  /** オノマトペ章専用：打鍵と同期する情景エフェクト（風/水/光）。 */
  fx?: OnomaFx;
}

export interface Story {
  key: string;
  title: string;
  chapter: string;
  /** 難易度（★1〜5）。 */
  difficulty: number;
  /** ノーミス達成時に付与するバッジ名。 */
  noMissBadge: string;
  /** 導入テキスト（数行）。 */
  intro: string[];
  questions: Question[];
}
