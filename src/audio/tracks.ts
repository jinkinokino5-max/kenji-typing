// 作品別 8bit BGM トラック定義。
// melody / bass は 1ステップ=8分音符相当。0 は休符。値は周波数(Hz)。
// コンボ強度(intensity 0..1)では音量のみが変化する（音高が上がっていく演出は不採用）。
//
// 【作曲方針】新規・改訂の作曲時は reference/BGM作曲方針.md に従うこと。
// 要点：16stepの単純ループでなく起承転結の4フレーズ（計64step目安）で作る／
// 賢治のライトモチーフ（度数5-6-1-6-5の弧形）を1箇所以上仕込む／
// ハーモニー声は常時（コンボ強度で音量が滑らかに増す）。
// 転調・ノイズドラム・オクターブ重ねは不採用（同ドキュメント §4・§6・改訂履歴）。

import { baseStoryKey } from "../data/split";

export interface BgmTrack {
  key: string;
  bpm: number;
  lead: OscillatorType;
  bassType: OscillatorType;
  /** 起→承→転→結の1ループ。64step目安（BGM作曲方針 §3）。 */
  melody: number[];
  bass: number[];
  leadVol: number;
  bassVol: number;
  /** リードに重ねる常時のハーモニー声。音量はコンボ強度で連続変化（同方針 §8）。 */
  harmony?: number[];
  harmonyVol?: number;
}

